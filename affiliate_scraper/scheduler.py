"""Windows Task Scheduler integration.

Generates a small ``.bat`` launcher plus the matching ``schtasks`` command.
By default it only PRINTS what it would do; ``--create`` runs ``schtasks`` (Windows only).
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
from pathlib import Path

TASK_NAME_RE = re.compile(r"^[A-Za-z0-9 _\-.]{1,100}$")
TIME_RE = re.compile(r"^([01]\d|2[0-3]):[0-5]\d$")


def build_bat(project_dir: Path, python_exe: str, config: str, log_file: str = r"logs\automation.log") -> str:
    return "\r\n".join([
        "@echo off",
        "REM Generated by: py main.py schedule  - runs the affiliate automation once",
        f'cd /d "{project_dir}"',
        'if not exist logs mkdir logs',
        f'"{python_exe}" main.py run --config "{config}" >> "{log_file}" 2>&1',
        "",
    ])


def build_vbs(bat_path: Path) -> str:
    """Runs the .bat with its window hidden (window style 0), so a scheduled run shows no CMD screen."""
    quoted = str(bat_path).replace('"', '""')
    return "\r\n".join([
        "' Generated by: py main.py schedule --hidden - runs the automation without a window",
        f'CreateObject("WScript.Shell").Run """{quoted}""", 0, True',
        "",
    ])


def build_schtasks_create(task_name: str, bat_path: Path, every: str = "daily", at: str = "08:17",
                          hours: int = 6, vbs_path: Path | None = None) -> list[str]:
    if not TASK_NAME_RE.match(task_name):
        raise ValueError("task name may contain letters, digits, space, _ - . only")
    if not TIME_RE.match(at):
        raise ValueError("time must be HH:MM (24h)")
    action = f'wscript.exe "{vbs_path}"' if vbs_path else f'"{bat_path}"'
    cmd = ["schtasks", "/Create", "/TN", task_name, "/TR", action, "/F"]
    if every == "daily":
        cmd += ["/SC", "DAILY", "/ST", at]
    elif every == "hourly":
        if not 1 <= hours <= 23:
            raise ValueError("hours must be 1-23")
        cmd += ["/SC", "HOURLY", "/MO", str(hours), "/ST", at]
    elif every == "twice-daily":
        # every 12 hours from the start time, e.g. 08:13 and 20:13
        cmd += ["/SC", "HOURLY", "/MO", "12", "/ST", at]
    elif every == "weekly":
        cmd += ["/SC", "WEEKLY", "/D", "MON", "/ST", at]
    else:
        raise ValueError("every must be daily, twice-daily, hourly or weekly")
    return cmd


def build_schtasks_delete(task_name: str) -> list[str]:
    if not TASK_NAME_RE.match(task_name):
        raise ValueError("bad task name")
    return ["schtasks", "/Delete", "/TN", task_name, "/F"]


def run_schtasks(cmd: list[str]) -> int:
    if os.name != "nt":
        print("schtasks is only available on Windows - command not executed.", file=sys.stderr)
        return 1
    # list form: no shell, no injection. Output goes through Python so the dashboard can show it.
    r = subprocess.run(cmd, check=False, capture_output=True, text=True,
                       creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
    for text, stream in ((r.stdout, sys.stdout), (r.stderr, sys.stderr)):
        if text.strip():
            print(text.strip(), file=stream)
    return r.returncode


def console_python(exe: str) -> str:
    """pythonw.exe (no console) -> python.exe next to it, for the .bat that logs the run to a file."""
    p = Path(exe)
    if p.name.lower() == "pythonw.exe" and (p.parent / "python.exe").exists():
        return str(p.parent / "python.exe")
    return exe
